-- STATEMENT 7: GetLowStockProductsAsync
-- Source Location: ProductRepository.cs, Method: GetLowStockProductsAsync
-- Statement Type: SELECT with CTE and Window Functions (AVG, MIN, MAX OVER)
-- Description: Retrieves low stock products with stock analysis using window aggregates
-- Parameters: @Threshold (INT)
-- ============================================

WITH StockAnalysis AS (
    SELECT 
        p.*,
        AVG(StockQuantity) OVER() as AvgStock,
        MIN(StockQuantity) OVER() as MinStock,
        MAX(StockQuantity) OVER() as MaxStock
    FROM Products p
)
SELECT 
    sa.*,
    CASE 
        WHEN StockQuantity <= @Threshold THEN 'Critical'
        WHEN StockQuantity <= AvgStock * 0.5 THEN 'Low'
        ELSE 'Adequate'
    END as StockStatus,
    ROUND((StockQuantity / AvgStock) * 100, 2) as StockPercentageOfAverage
FROM StockAnalysis sa
WHERE StockQuantity <= @Threshold
ORDER BY StockQuantity;

